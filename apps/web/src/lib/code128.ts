const START_B = 104, STOP = 106;

/** 값 → 막대·공백 폭(첫 칸은 막대). 코드 세트 B 밖의 글자는 '?'로 바꾼다 */
export function code128Widths(text: string): number[] {
  const vals = [...text].map((ch) => { const c = ch.charCodeAt(0); return c >= 32 && c <= 126 ? c - 32 : 31; });
  const check = vals.reduce((sum, v, i) => sum + v * (i + 1), START_B) % 103;
  return [START_B, ...vals, check, STOP].flatMap((v) => [...PATTERNS[v]].map(Number));
}
